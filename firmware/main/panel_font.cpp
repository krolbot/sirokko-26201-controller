const Glyph& glyph(uint32_t codepoint) {
    codepoint = cyrillic_ascii_equivalent(codepoint);
    for (const Entry& entry : kGlyphs) {
        if (entry.codepoint == codepoint) return entry.glyph;
    }
    return kFallback;
}

const char* next_utf8(const char* text, uint32_t* codepoint) {
    if (!text || !codepoint) return text;
    const auto* bytes = reinterpret_cast<const unsigned char*>(text);
    const unsigned char first = bytes[0];
    if (first < 0x80U) {
        *codepoint = first;
        return text + 1;
    }
    if (first >= 0xC2U && first <= 0xDFU && continuation(bytes[1])) {
        *codepoint = (static_cast<uint32_t>(first & 0x1FU) << 6U) | (bytes[1] & 0x3FU);
        return text + 2;
    }
    if (first >= 0xE0U && first <= 0xEFU && continuation(bytes[1]) && continuation(bytes[2])) {
        *codepoint = (static_cast<uint32_t>(first & 0x0FU) << 12U) |
                     (static_cast<uint32_t>(bytes[1] & 0x3FU) << 6U) | (bytes[2] & 0x3FU);
        return text + 3;
    }
    if (first >= 0xF0U && first <= 0xF4U && continuation(bytes[1]) && continuation(bytes[2]) &&
        continuation(bytes[3])) {
        *codepoint = (static_cast<uint32_t>(first & 0x07U) << 18U) |
                     (static_cast<uint32_t>(bytes[1] & 0x3FU) << 12U) |
                     (static_cast<uint32_t>(bytes[2] & 0x3FU) << 6U) | (bytes[3] & 0x3FU);
        return text + 4;
    }
    *codepoint = '?';
    return text + 1;
}

