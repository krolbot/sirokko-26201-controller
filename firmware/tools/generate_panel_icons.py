#!/usr/bin/env python3
"""Rasterize approved TFT SVG icon paths into deterministic 4-bit alpha masks.

All geometry below is transcribed from sirokko_tft_states/render.py (and the filled
thermometer from sirokko_tft_gauge/render.py).  librsvg supplies the development-time
SVG rasterizer only; firmware samples the generated masks without a renderer.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import sys
import tempfile

try:
    from PIL import Image
except ImportError as exc:  # pragma: no cover - setup diagnostic
    raise SystemExit("Pillow is required to read librsvg PNG output") from exc


MASK_SIZE = 96
# Enum order is part of panel_draw::Icon; do not reorder these entries.
ICONS = (
    ("Clock", '<circle cx="12" cy="12" r="8.5"/><path d="M12 7v5l3 2"/>'),
    ("Settings", '<path d="M4 7h16M4 17h16"/><rect x="7" y="4" width="4" height="6" rx="1" fill="#000" stroke="none"/><rect x="14" y="14" width="4" height="6" rx="1" fill="#000" stroke="none"/>'),
    ("Warning", '<path d="M12 3 2 21h20zM12 9v5M12 17v.2"/>'),
    ("Thermometer", '<path d="M9 14V5a3 3 0 0 1 6 0v9a5 5 0 1 1-6 0ZM12 8v10"/>'),
    ("ThermometerFilled", '<path fill="#000" stroke="none" fill-rule="evenodd" d="M 5 11 V 3 A 3 3 0 0 1 11 3 V 11 A 5 5 0 1 1 5 11 Z M 7 3 A 1 1 0 0 1 9 3 V 8 H 7 Z"/>'),
    ("Upload", '<path d="M12 16V3m-5 5 5-5 5 5M4 15v6h16v-6"/>'),
    ("Wifi", '<path d="M3 8a14 14 0 0 1 18 0M6 12a9 9 0 0 1 12 0M9 16a4 4 0 0 1 6 0M12 20h.01"/>'),
    ("Check", '<path d="m5 12 4 4 10-10"/>'),
    ("Power", '<path d="M12 3v9M7 5.5a8 8 0 1 0 10 0"/>'),
    ("Stop", '<rect x="6" y="6" width="12" height="12" rx="1"/>'),
    ("Heat", '<path d="M6 21V17M12 21V17M18 21V17M6 3C1 7 11 9 6 13M12 3C7 7 17 9 12 13M18 3C13 7 23 9 18 13"/>'),
    ("Fan", '<circle cx="12" cy="12" r="2"/><path d="M12 10C6 8 8 1 13 2C17 3 14 8 12 10ZM14 12C16 6 23 8 22 13C21 17 16 14 14 12ZM12 14C18 16 16 23 11 22C7 21 10 16 12 14ZM10 12C8 18 1 16 2 11C3 7 8 10 10 12Z"/>'),
    ("Chevron", '<path d="m8 7 5 5-5 5"/>'),
)


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def svg(body: str) -> str:
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">'
        '<g fill="none" stroke="#000" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">'
        + body + '</g></svg>'
    )


def packed_4bpp(values: bytes) -> bytes:
    levels = [(value + 8) // 17 for value in values]
    return bytes((levels[index] << 4) | (levels[index + 1] if index + 1 < len(levels) else 0)
                 for index in range(0, len(levels), 2))


def rasterize(name: str, body: str) -> bytes:
    # TMPDIR is Hermes profile scratch during development.  No generated PNG enters the repo.
    with tempfile.TemporaryDirectory(prefix="panel-icon-") as temp:
        root = Path(temp)
        source = root / f"{name}.svg"
        rendered = root / f"{name}.png"
        source.write_text(svg(body), encoding="utf-8", newline="\n")
        subprocess.run(
            ["rsvg-convert", "--width", str(MASK_SIZE), "--height", str(MASK_SIZE),
             "--output", str(rendered), str(source)],
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        image = Image.open(rendered).convert("RGBA")
        if image.size != (MASK_SIZE, MASK_SIZE):
            raise RuntimeError(f"unexpected raster dimensions for {name}: {image.size}")
        return packed_4bpp(image.getchannel("A").tobytes())


def emit_bytes(name: str, values: bytes) -> list[str]:
    lines = [f"static const uint8_t {name}[] = {{"]
    for start in range(0, len(values), 16):
        lines.append("    " + ", ".join(f"0x{value:02X}" for value in values[start:start + 16]) + ",")
    lines.append("};")
    return lines


def generate() -> str:
    output = [
        "// Generated by firmware/tools/generate_panel_icons.py; do not edit.",
        "// 96x96 4-bit alpha masks from the approved local TFT SVG paths.",
        "namespace icon_data {",
    ]
    names = []
    for name, body in ICONS:
        values = rasterize(name, body)
        symbol = f"k{name}"
        output.extend(emit_bytes(symbol, values))
        names.append(symbol)
    output.append("static const IconMask kIcons[] = {")
    for name in names:
        output.append(f"    {{{name}, {MASK_SIZE}U, {MASK_SIZE}U}},")
    output.append("};")
    output.append(f"static constexpr uint8_t kIconCount = {len(names)}U;")
    output.append("}  // namespace icon_data")
    output.append("")
    return "\n".join(output)


def main() -> int:
    root = repo_root()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=root / "firmware/main/panel_icons_data.inc")
    parser.add_argument("--check", action="store_true", help="fail instead of rewriting when output differs")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != generated:
            print(f"OUT-OF-DATE: {args.output}", file=sys.stderr)
            return 1
        print(f"OK: {args.output}")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated, encoding="utf-8", newline="\n")
    print(f"Wrote {args.output} ({len(generated.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
