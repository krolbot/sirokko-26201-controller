#!/usr/bin/env python3
"""Generate deterministic 4-bit Roboto bitmap faces for panel_canvas.cpp.

The asset is the OFL-licensed variable Roboto copy in firmware/assets.  The approved
TFT reference uses its normal width axis and weights 400/500; this generator pins
those same axes and emits baseline-relative glyph metrics plus 1/64-pixel advances.
Runtime code only reads the generated C++ data and never needs Python, FreeType, or
font files.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys

try:
    from PIL import ImageFont
except ImportError as exc:  # pragma: no cover - setup diagnostic
    raise SystemExit("Pillow with FreeType support is required to generate panel fonts") from exc


SIZES = (12, 13, 14, 15, 16, 17, 18, 19, 20, 22, 24, 27, 34, 40, 44, 57)
FULL_SIZES = frozenset((12, 13, 14, 15, 16, 17, 18, 19, 20, 22, 24, 27, 34))
WEIGHTS = (400, 500)

# ASCII covers Wi-Fi credentials verbatim.  The remaining set covers every Russian
# upper/lowercase letter (including Ё/ё), degree, bullet, en/em dashes and arrows.
FULL_CODEPOINTS = tuple(sorted(
    set(range(0x20, 0x7F))
    | {0x00B0, 0x2013, 0x2014, 0x2022, 0x2190, 0x2191, 0x2192, 0x2193, 0x0401, 0x0451}
    | set(range(0x0410, 0x0450))
))

# Large original-SVG faces are used for values.  A visible '?' is kept in every
# face, so an unsupported large caption has a defined fallback rather than UB.
BIG_CODEPOINTS = tuple(sorted({ord(ch) for ch in " ?0123456789.,:+-/%°Cчмин"}))


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def packed_4bpp(mask: bytes) -> bytes:
    levels = [(value + 8) // 17 for value in mask]
    packed = bytearray()
    for index in range(0, len(levels), 2):
        high = levels[index]
        low = levels[index + 1] if index + 1 < len(levels) else 0
        packed.append((high << 4) | low)
    return bytes(packed)


def font_face(font_path: Path, pixel_size: int, weight: int, codepoints: tuple[int, ...]):
    font = ImageFont.truetype(str(font_path), size=pixel_size)
    axes = font.get_variation_axes()
    if len(axes) != 2 or axes[0]["minimum"] > weight or axes[0]["maximum"] < weight:
        raise RuntimeError("Roboto variable Weight axis is unavailable")
    if axes[1]["minimum"] > 100 or axes[1]["maximum"] < 100:
        raise RuntimeError("Roboto variable Width axis does not contain normal width 100")
    # Axis order/values follow the approved render.py exactly: [weight, width].
    font.set_variation_by_axes([weight, 100])
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    glyphs = []
    fallback_index = None
    for index, codepoint in enumerate(codepoints):
        character = chr(codepoint)
        mask, offset = font.getmask2(character, mode="L", anchor="ls")
        width, height = mask.size
        raw = bytes(mask)
        if len(raw) != width * height:
            raise RuntimeError(f"unexpected mask size for U+{codepoint:04X}")
        encoded = packed_4bpp(raw)
        advance_64 = round(font.getlength(character) * 64)
        bearing_x, bearing_y = offset
        if not (-32768 <= advance_64 <= 32767 and -32768 <= bearing_x <= 32767 and
                -32768 <= bearing_y <= 32767 and 0 <= width <= 255 and 0 <= height <= 255):
            raise RuntimeError(f"metric does not fit generated layout for U+{codepoint:04X}")
        glyphs.append((codepoint, len(bitmap), len(encoded), advance_64, bearing_x, bearing_y, width, height))
        bitmap.extend(encoded)
        if codepoint == ord("?"):
            fallback_index = index
    if fallback_index is None:
        raise RuntimeError("every generated face needs '?' fallback")
    return ascent, descent, bytes(bitmap), glyphs, fallback_index


def emit_bytes(name: str, values: bytes) -> list[str]:
    lines = [f"static const uint8_t {name}[] = {{"]
    for start in range(0, len(values), 16):
        row = ", ".join(f"0x{value:02X}" for value in values[start:start + 16])
        lines.append(f"    {row},")
    lines.append("};")
    return lines


def generate(font_path: Path) -> str:
    digest = hashlib.sha256(font_path.read_bytes()).hexdigest()
    output = [
        "// Generated by firmware/tools/generate_panel_fonts.py; do not edit.",
        f"// Roboto.ttf SHA-256: {digest}",
        "// 4-bit alpha masks; bearings are baseline-relative; advances are in 1/64 px.",
        "// Approved scaled SVG sizes map 13.90 -> 14 px, 14.53 -> 15 px, 44.03 -> 44 px.",
        "namespace font_data {",
    ]
    faces = []
    for pixel_size in SIZES:
        codepoints = FULL_CODEPOINTS if pixel_size in FULL_SIZES else BIG_CODEPOINTS
        for weight in WEIGHTS:
            ascent, descent, bitmap, glyphs, fallback_index = font_face(font_path, pixel_size, weight, codepoints)
            stem = f"{pixel_size}_{weight}"
            bitmap_name = f"kBitmap_{stem}"
            glyph_name = f"kGlyphs_{stem}"
            output.extend(emit_bytes(bitmap_name, bitmap))
            output.append(f"static const FontGlyph {glyph_name}[] = {{")
            for codepoint, offset, length, advance, bearing_x, bearing_y, width, height in glyphs:
                output.append(
                    f"    {{0x{codepoint:04X}U, {offset}U, {length}U, {advance}, "
                    f"{bearing_x}, {bearing_y}, {width}U, {height}U}},"
                )
            output.append("};")
            faces.append((pixel_size, weight, ascent, descent, glyph_name, len(glyphs), bitmap_name, len(bitmap), fallback_index))
    output.append("static const FontFace kFaces[] = {")
    for pixel_size, weight, ascent, descent, glyph_name, glyph_count, bitmap_name, bitmap_count, fallback_index in faces:
        output.append(
            f"    {{{pixel_size}U, {weight}U, {ascent}, {descent}, {glyph_name}, {glyph_count}U, "
            f"{bitmap_name}, {bitmap_count}U, {fallback_index}U}},"
        )
    output.append("};")
    output.append(f"static constexpr uint16_t kFaceCount = {len(faces)}U;")
    output.append("}  // namespace font_data")
    output.append("")
    return "\n".join(output)


def main() -> int:
    root = repo_root()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=root / "firmware/assets/Roboto.ttf")
    parser.add_argument("--output", type=Path, default=root / "firmware/main/panel_fonts_data.inc")
    parser.add_argument("--check", action="store_true", help="fail instead of rewriting when output differs")
    args = parser.parse_args()
    if not args.font.is_file():
        raise SystemExit(f"font not found: {args.font}")
    license_path = args.font.with_name("OFL-Roboto.txt")
    if not license_path.is_file():
        raise SystemExit(f"Roboto OFL license not found beside font: {license_path}")
    generated = generate(args.font)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != generated:
            print(f"OUT-OF-DATE: {args.output}", file=sys.stderr)
            return 1
        print(f"OK: {args.output}")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated, encoding="utf-8", newline="\n")
    print(f"Wrote {args.output} ({len(generated.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
