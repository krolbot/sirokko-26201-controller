#!/usr/bin/env python3
"""Deterministically embed the built offline web page; ESP-IDF needs no Node.js at build/run time."""
from pathlib import Path
import argparse
import gzip
import hashlib
import io
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / 'web_ui/dist/index.html'
DEFAULT_OUTPUT = ROOT / 'main/web_ui_data.inc'


def render(source: bytes) -> str:
    if not source or len(source) > 4 * 1024 * 1024:
        raise ValueError('web page is empty or exceeds the 4 MiB source bound')
    html = source.decode('utf-8')
    if '<html' not in html.lower() or '</html>' not in html.lower():
        raise ValueError('input is not a complete built HTML document')
    if re.search(r'<script\b[^>]*\bsrc\s*=', html, re.I):
        raise ValueError('shipping page must inline its scripts')
    if re.search(r'<link\b[^>]*\brel=["\']stylesheet["\'][^>]*\bhref=', html, re.I):
        raise ValueError('shipping page must inline its stylesheets')
    stream = io.BytesIO()
    with gzip.GzipFile(fileobj=stream, mode='wb', filename='', mtime=0, compresslevel=9) as zipped:
        zipped.write(source)
    compressed = stream.getvalue()
    if len(compressed) > 768 * 1024:
        raise ValueError('compressed web page exceeds the firmware flash budget')
    assert gzip.decompress(compressed) == source
    lines = ['// Generated by firmware/tools/embed_web_ui.py; do not edit.',
             '// HTML SHA-256: ' + hashlib.sha256(source).hexdigest(),
             '// GZIP SHA-256: ' + hashlib.sha256(compressed).hexdigest(),
             'alignas(4) static constexpr uint8_t kPageGzip[] = {']
    for offset in range(0, len(compressed), 20):
        lines.append('    ' + ','.join(f'0x{byte:02x}' for byte in compressed[offset:offset + 20]) + ',')
    lines.extend(['};', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, default=DEFAULT_INPUT)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        generated = render(args.input.read_bytes())
        if args.check:
            if args.output.read_text() != generated:
                raise ValueError('embedded page differs from built frontend; regenerate before publishing')
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(generated, encoding='utf-8')
        print(f'PASS: {args.output}; deterministic self-contained gzip page; check={args.check}')
    except (OSError, UnicodeError, ValueError) as error:
        print(f'embed_web_ui.py: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
