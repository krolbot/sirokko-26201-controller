#pragma once

#include <array>
#include <cstdint>

namespace sirokko::calibration {

// The implementation intentionally keeps all storage bounded and allocation-free.
constexpr uint8_t kRequiredAnalysisWindows = 3;
constexpr uint8_t kMaximumSamplesPerWindow = 64;
constexpr uint8_t kMaximumTestedPoints = 16;
constexpr uint16_t kMaximumHistorySamples =
    static_cast<uint16_t>(kRequiredAnalysisWindows) * kMaximumSamplesPerWindow;

struct TemperatureSample {
    int32_t milli_c{};
    uint64_t sample_ms{};
    uint8_t status{};  // Zero means the acquisition layer reported no fault.
    bool valid{};
};

// All command fields describe commands actually applied by the parent controller.
// commanded_code is deliberately not a calibration request: it is the achieved code.
struct Observation {
    uint64_t now_ms{};
    TemperatureSample exhaust;
    TemperatureSample hot_air;
    uint16_t commanded_code{};
    bool run_active{};
    bool fuel_commanded{};
    bool glow_commanded{};
    // A debounced one-tick negative report from KEY0 or an equivalent input.
    bool operator_negative{};
};

enum class Phase : uint8_t {
    IDLE,
    WAIT_REFERENCE_COMMAND,
    SETTLE_REFERENCE,
    WAIT_DESCENT_COMMAND,
    SETTLE_POINT,
    WAIT_RETURN_COMMAND,
    SETTLE_RETURN_REFERENCE,
    WAIT_REPEAT_COMMAND,
    SETTLE_REPEAT_POINT,
    WAIT_POST_REPEAT_REFERENCE_COMMAND,
    SETTLE_POST_REPEAT_REFERENCE,
    COMPLETE_PENDING_STOP,
    FAILED,
    CANCELLED,
};

enum class Reason : uint8_t {
    NONE,
    COMPLETE,
    INVALID_CONFIG,
    ALREADY_ACTIVE,
    BACKDATED_TIME,
    OVERALL_TIMEOUT,
    RUN_CONTEXT_LOST,
    COMMAND_OUT_OF_RANGE,
    COMMAND_SLEW_VIOLATION,
    COMMAND_NOT_REACHED,
    SENSOR_INVALID,
    STALE_SAMPLE,
    SAMPLE_TIMESTAMP_REGRESSION,
    SAMPLE_SKEW,
    REPEATED_SAMPLE,
    SAMPLE_GAP,
    REFERENCE_TIMEOUT,
    POINT_TIMEOUT,
    REFERENCE_NOT_REPRODUCIBLE,
    NO_COMMAND_RESPONSE,
    POINT_NOT_REPRODUCIBLE,
    DYNAMIC_NOT_REPRODUCIBLE,
    INSUFFICIENT_MARGIN,
    OPERATOR_NEGATIVE,
    EXTERNAL_CANCEL,
};

// Every numeric setting is a process/service input.  This module supplies no
// physical ignition, overheating, minimum-PWM, or flame-loss threshold.
struct Config {
    // Closed research interval. The reference is always the tested upper end.
    uint16_t floor_code{};
    uint16_t ceiling_code{};
    uint16_t step_code{};

    // Three non-overlapping analysis windows are kept. A common prototype is
    // 60 samples at 1 s, but those are supplied by the caller rather than hidden.
    uint8_t samples_per_window{};
    uint64_t sample_period_ms{};
    uint64_t maximum_sample_gap_ms{};
    uint64_t maximum_sample_age_ms{};
    uint64_t maximum_no_new_sample_ms{};
    uint64_t maximum_channel_skew_ms{};

    uint64_t command_arrival_timeout_ms{};
    uint64_t reference_timeout_ms{};
    uint64_t point_timeout_ms{};
    uint64_t maximum_total_duration_ms{};
    uint64_t maximum_transition_settle_difference_ms{};

    // Reference-derived bands are fixed once and never widened by a lower point.
    uint32_t reference_noise_floor_milli_c{};
    uint32_t reference_noise_ceiling_milli_c{};
    uint32_t reference_drift_floor_milli_c{};
    uint32_t reference_drift_ceiling_milli_c{};
    uint32_t minimum_command_response_milli_c{};
    uint8_t reference_noise_multiplier{};
    uint8_t reference_drift_multiplier{};
    uint8_t repeat_mean_multiplier{};
    uint8_t response_multiplier{};

    // Acceptance ceilings for the parent limiter's actually achieved motion.
    // They are not generated by the calibrator and are not physical limits.
    double maximum_slew_up_codes_per_s{};
    double maximum_slew_down_codes_per_s{};
};

struct PointSummary {
    int32_t exhaust_mean_milli_c{};
    int32_t hot_air_mean_milli_c{};
    uint32_t exhaust_max_window_drift_milli_c{};
    uint32_t hot_air_max_window_drift_milli_c{};
    uint32_t exhaust_max_window_noise_milli_c{};
    uint32_t hot_air_max_window_noise_milli_c{};
    uint32_t exhaust_window_mean_span_milli_c{};
    uint32_t hot_air_window_mean_span_milli_c{};
    uint64_t settled_after_ms{};
};

struct TestedPoint {
    uint16_t code{};
    PointSummary first;
    PointSummary repeat;
};

struct Profile {
    bool valid{};
    uint16_t min_code{};  // One successfully repeated lower point remains below this margin-bearing limit.
    uint16_t max_code{};  // The tested reference code, never an untested Config ceiling extension.
    double tested_slew_up_codes_per_s{};
    double tested_slew_down_codes_per_s{};
    PointSummary reference;
    uint32_t exhaust_fixed_noise_band_milli_c{};
    uint32_t hot_air_fixed_noise_band_milli_c{};
    uint32_t exhaust_fixed_drift_band_milli_c{};
    uint32_t hot_air_fixed_drift_band_milli_c{};
    uint8_t tested_point_count{};
    std::array<TestedPoint, kMaximumTestedPoints> tested_points{};
};

struct Result {
    bool completed{};
    Reason reason{Reason::NONE};
    Profile profile{};
};

struct Snapshot {
    Phase phase{Phase::IDLE};
    Reason reason{Reason::NONE};
    // Request for the parent controller. It must apply its own safe slew limiter.
    uint16_t target_code{};
    uint8_t accepted_point_count{};
    uint64_t elapsed_ms{};
    bool active{};
    // Parent must route this to its STOP/fuel-cutoff/cooldown FSM; this class never drives outputs.
    bool stop_requested{};
    // True only after a complete profile exists and while the parent is stopping/cooling down.
    bool completed_pending_stop{};
    Result result{};
};

class Calibrator {
public:
    // Call only after the parent FSM has completed normal ignition and entered RUN.
    // Invalid configuration is rejected fail-closed and requests STOP.
    bool start(const Config& config, uint64_t now_ms);
    Snapshot tick(const Observation& observation);
    void cancel(Reason reason = Reason::EXTERNAL_CANCEL);
    Snapshot snapshot(uint64_t now_ms) const;
    bool active() const;

private:
    struct RecordedSample {
        uint64_t sample_ms{};
        int32_t exhaust_milli_c{};
        int32_t hot_air_milli_c{};
    };

    bool valid_config(const Config& config) const;
    bool validate_context(const Observation& observation);
    bool validate_samples(const Observation& observation);
    bool observe_command_slew(const Observation& observation);
    bool record_sample_if_due(const Observation& observation);
    bool analyze_history(PointSummary* summary) const;
    bool establish_reference(const PointSummary& summary);
    bool stable_against_reference(const PointSummary& summary) const;
    bool reference_matches(const PointSummary& expected, const PointSummary& observed) const;
    bool point_matches(const PointSummary& first, const PointSummary& repeat) const;
    bool has_command_response(const PointSummary& from, const PointSummary& to) const;
    bool transition_is_repeatable(const PointSummary& before_first, const PointSummary& first,
                                  const PointSummary& returned, const PointSummary& repeat) const;
    void begin_wait(Phase phase, uint16_t target_code, uint64_t now_ms);
    void begin_settle(Phase phase, uint64_t now_ms);
    void clear_history();
    void add_sample(const RecordedSample& sample);
    void fail(Phase terminal_phase, Reason reason);
    void complete();
    uint64_t phase_elapsed(uint64_t now_ms) const;
    uint16_t next_lower_code(uint16_t current_code) const;

    Config config_{};
    Phase phase_{Phase::IDLE};
    Reason reason_{Reason::NONE};
    Result result_{};
    uint64_t started_ms_{};
    uint64_t phase_started_ms_{};
    uint64_t last_now_ms_{};
    uint64_t last_exhaust_sample_ms_{};
    uint64_t last_hot_air_sample_ms_{};
    uint64_t last_new_sample_seen_at_ms_{};
    uint64_t last_command_observed_ms_{};
    uint16_t target_code{};
    uint16_t current_point_code_{};
    uint16_t last_command_code_{};
    uint8_t accepted_point_count_{};
    bool have_sample_timestamps_{};
    bool have_command_observation_{};
    PointSummary reference_{};
    PointSummary pre_point_reference_{};
    PointSummary first_point_{};
    PointSummary returned_reference_{};
    uint32_t exhaust_noise_band_milli_c_{};
    uint32_t hot_air_noise_band_milli_c_{};
    uint32_t exhaust_drift_band_milli_c_{};
    uint32_t hot_air_drift_band_milli_c_{};
    double slew_up_credit_codes_{1.0};
    double slew_down_credit_codes_{1.0};
    double observed_slew_up_codes_per_s_{};
    double observed_slew_down_codes_per_s_{};
    std::array<RecordedSample, kMaximumHistorySamples> history_{};
    uint16_t history_count_{};
    std::array<TestedPoint, kMaximumTestedPoints> accepted_points_{};
};

const char* phase_name(Phase phase);
const char* reason_name(Reason reason);

}  // namespace sirokko::calibration
