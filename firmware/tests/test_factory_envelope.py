#!/usr/bin/env python3
"""Offline factory encoding tests; all values here are synthetic, not heater settings."""
import importlib.util
import json
import pathlib
import subprocess
import tempfile

FIRMWARE = pathlib.Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('factory', FIRMWARE/'tools/prepare_factory_envelope.py')
assert spec is not None and spec.loader is not None
factory = importlib.util.module_from_spec(spec)
spec.loader.exec_module(factory)


def synthetic_spec():
    envelope = dict.fromkeys(factory.TIMES, 100)
    envelope.update(maximum_purge_exit_exhaust_milli_c=60000, maximum_purge_exit_air_milli_c=50000,
                    maximum_exhaust_milli_c=500000, maximum_air_milli_c=250000,
                    minimum_ignition_rise_milli_c=10000, minimum_run_exhaust_milli_c=110000,
                    minimum_ignition_air_rise_milli_c=5000, purge_speed_code=1400,
                    reference_speed_code=1000, exploration_floor_code=400)
    return {'qualification_reference': 'SYNTHETIC TEST ONLY — NOT QUALIFIED FOR HARDWARE', 'envelope': envelope}


def main():
    with tempfile.TemporaryDirectory(prefix='sirokko-factory-test-') as temporary:
        root = pathlib.Path(temporary)
        source = root/'input.json'
        data = synthetic_spec()
        source.write_text(json.dumps(data))
        assert factory.read_spec(source) == data
        for bad in [dict(data, extra=1), dict(data, qualification_reference=''),
                    dict(data, envelope=dict(data['envelope'], preheat_ms=True)),
                    dict(data, envelope=dict(data['envelope'], purge_speed_code=65536)),
                    dict(data, envelope=dict(data['envelope'], ignition_ms=-1))]:
            source.write_text(json.dumps(bad))
            try:
                factory.read_spec(source)
            except ValueError:
                pass
            else:
                raise AssertionError('invalid specification accepted')
        source.write_text('{"envelope":{},"envelope":{},"qualification_reference":"x"}')
        try:
            factory.read_spec(source)
        except ValueError:
            pass
        else:
            raise AssertionError('duplicate keys accepted')
        data_bytes, layout = factory.make_blob(data, root, 'xtensa-esp32s3-elf-g++',
                                             'xtensa-esp32s3-elf-objcopy', 'g++')
        assert data_bytes == factory.make_blob(data, root, 'xtensa-esp32s3-elf-g++',
                                               'xtensa-esp32s3-elf-objcopy', 'g++')[0]
        blob = root/'target.bin'
        blob.write_bytes(data_bytes)
        # Execute the actual decoder/semantic validator on target-generated bytes.
        # Layout equality is asserted; host layout is never used to CREATE the blob.
        decoder = root/'decode.cpp'
        decoder.write_text('''#include "sirokko/control.hpp"
#include "record_codec.hpp"
#include <fstream>
#include <cassert>
int main(int argc,char** argv) {
    using R=record_codec::Record<sirokko::SafetyEnvelope>;
    static_assert(sizeof(R)==SIZE && offsetof(R,checksum)==OFFSET);
    R record{}; std::ifstream stream(argv[1],std::ios::binary);
    stream.read(reinterpret_cast<char*>(&record),sizeof(record));
    assert(stream.gcount()==sizeof(record));
    assert(record_codec::valid(record,0x454E5631,sizeof(record)));
    assert(sirokko::valid_safety_envelope(record.value));
    assert(record.value.preheat_ms==100 && record.value.reference_speed_code==1000);
    record.value.reference_speed_code=999;
    assert(!record_codec::valid(record,0x454E5631,sizeof(record)));
}'''.replace('SIZE', str(layout[0])).replace('OFFSET', str(layout[1])))
        factory.run(['g++', '-std=c++20', '-I', FIRMWARE/'components/control_core/include',
                     '-I', FIRMWARE/'main', decoder, FIRMWARE/'components/control_core/profile.cpp', '-o', root/'decode'])
        factory.run([root/'decode', blob])
        source.write_text(json.dumps(data))
        output = root/'prepared'
        factory.run(['python3', FIRMWARE/'tools/prepare_factory_envelope.py',
                     '--input', source, '--output-dir', output])
        assert (output/'envelope_v1.bin').read_bytes() == data_bytes
        manifest = json.loads((output/'manifest.json').read_text())
        assert manifest['physical_qualification_verified_by_tool'] is False
        import os
        generator = pathlib.Path(os.environ['IDF_PATH'])/'components/nvs_flash/nvs_partition_generator/nvs_partition_gen.py'
        subprocess.run(['python3', str(generator), 'generate', 'envelope.csv', 'synthetic-nvs.bin', '0x6000'],
                       cwd=output, check=True, timeout=60)
        assert (output/'synthetic-nvs.bin').stat().st_size == 0x6000
        bad = synthetic_spec()
        bad['envelope']['reference_speed_code'] = 0
        try:
            factory.make_blob(bad, root, 'xtensa-esp32s3-elf-g++', 'xtensa-esp32s3-elf-objcopy', 'g++')
        except subprocess.CalledProcessError:
            pass
        else:
            raise AssertionError('semantically invalid envelope accepted')
        print('PASS: strict JSON; semantic rejection; target ABI; deterministic blob; real record decoder; corruption rejection')


if __name__ == '__main__':
    main()
